import { createSignal, createEffect } from 'solid-js';
import { IconTerminal2, IconAlertCircle, IconCheck } from '@tabler/icons-solidjs';
import type { Plan } from '../types';

interface ReloadDrawerProps {
  open: boolean;
  currentPlan: Plan | null;
  onClose: () => void;
  onApply: (plan: Plan) => void;
}

export default function ReloadDrawer(props: ReloadDrawerProps) {
  const [jsonVal, setJsonVal] = createSignal('');
  const [statusText, setStatusText] = createSignal('');
  const [statusType, setStatusType] = createSignal<'success' | 'error' | ''>('');

  createEffect(() => {
    if (props.open) {
      setJsonVal(props.currentPlan ? JSON.stringify(props.currentPlan, null, 2) : '');
      setStatusText('');
      setStatusType('');
    }
  });

  function validatePlan(data: any): string | null {
    if (typeof data !== 'object' || data === null) {
      return 'Payload must be a JSON object.';
    }
    if (!Array.isArray(data.tasks)) {
      return 'Payload must include a "tasks" array.';
    }
    for (const task of data.tasks) {
      if (typeof task.id === 'undefined') {
        return 'Each task must have an "id".';
      }
      if (typeof task.title !== 'string') {
        return 'Each task must have a "title" string.';
      }
    }
    return null;
  }

  function handleLoad() {
    const raw = jsonVal().trim();
    if (!raw) {
      setStatusText('Paste a JSON payload first.');
      setStatusType('error');
      return;
    }

    let parsed: any;
    try {
      parsed = JSON.parse(raw);
    } catch (e: any) {
      setStatusText(`Invalid JSON — ${e.message}`);
      setStatusType('error');
      return;
    }

    const error = validatePlan(parsed);
    if (error) {
      setStatusText(error);
      setStatusType('error');
      return;
    }

    props.onApply(parsed as Plan);
    setStatusText('Plan loaded successfully.');
    setStatusType('success');

    setTimeout(() => {
      props.onClose();
    }, 600);
  }

  return (
    <div
      class={`drawer-overlay ${props.open ? 'open' : ''}`}
      onClick={(e) => e.target === e.currentTarget && props.onClose()}
    >
      <div class="drawer">
        <div class="drawer-header">
          <IconTerminal2 class="drawer-header-icon" size="22" stroke={1.8} />
          <h3>Reload JSON</h3>
        </div>
        <p class="drawer-sub">
          Paste the structured payload generated by Antigravity. This will update today's plan.
        </p>

        <textarea
          id="json-input"
          value={jsonVal()}
          onInput={(e) => setJsonVal(e.currentTarget.value)}
          placeholder='{"date": "2026-06-15", "focus": "ship, learn, grow", "tasks": [...] }'
        />

        <div class={`drawer-status ${statusType()}`}>
          {statusType() === 'error' && <IconAlertCircle size="15" />}
          {statusType() === 'success' && <IconCheck size="15" />}
          <span>{statusText()}</span>
        </div>

        <div class="drawer-actions">
          <button class="ghost-btn" onClick={props.onClose}>
            Cancel
          </button>
          <button class="primary-btn" onClick={handleLoad}>
            Load plan
          </button>
        </div>
      </div>
    </div>
  );
}
